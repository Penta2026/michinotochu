const { test, expect } = require('@playwright/test');
const fs = require('node:fs');
test('sugoroku browser regression', async ({page,context})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',d=>d.accept());
 await context.grantPermissions(['clipboard-read','clipboard-write']);
 await page.goto('http://127.0.0.1:8765/');
 await page.waitForFunction(()=>typeof runSugoroku==='function'&&!document.body.classList.contains('pwa-starting'));
 await page.evaluate(()=>{showView('sug');setOrigin('sug',34.3992388,132.4406034,'広島試験地点');});
 await page.locator('#sugRadiusFree').fill('80');
 await page.locator('[data-target="sugCount"] button').count().then(async n=>{await page.evaluate(()=>document.getElementById('sugCount').value='6');});
 await page.locator('#sugVehicle').selectOption('125');
 await page.locator('#sug .action-main').click();
 await expect(page.locator('#sugResult .goal')).toBeVisible({timeout:60000});
 const result=await page.locator('#sugResult').innerText();
 const match=result.match(/全区間の推定走行距離：約([\d.]+)km/);
 expect(match).not.toBeNull();expect(Number(match[1])).toBeLessThanOrEqual(80);
 const stops=await page.locator('#sugResult .route-line').count();expect(stops).toBeGreaterThan(0);expect(stops).toBeLessThanOrEqual(6);
 const downloadPromise=page.waitForEvent('download');
 await page.locator('#sugResult .route-gpx').click();
 const download=await downloadPromise;const xml=fs.readFileSync(await download.path(),'utf8');
 expect(xml).toContain('BNAV-ITINERARY-1');expect((xml.match(/<rtept /g)||[]).length).toBe(stops+1);
 await page.locator('#sugResult .route-bnavi').click();
 await expect.poll(()=>page.evaluate(()=>navigator.clipboard.readText())).toBe(xml);
 await page.locator('#sugResult').getByRole('button',{name:'お気に入りに保存'}).click();
 await page.evaluate(()=>showView('favorites'));
 await expect(page.locator('#favoriteList .fav-card')).toHaveCount(1);
 await page.reload();await page.waitForFunction(()=>typeof showView==='function'&&!document.body.classList.contains('pwa-starting'));
 await page.evaluate(()=>showView('favorites'));await expect(page.locator('#favoriteList .fav-card')).toHaveCount(1);
 await page.evaluate(()=>{showView('sug');setOrigin('sug',34.3992388,132.4406034,'広島試験地点');document.getElementById('sugRadiusFree').value='80';});
 await page.locator('#sug .action-main').click();await expect(page.locator('#sugResult .goal')).toBeVisible({timeout:60000});
 await page.locator('#sugResult .detour-open').click();await expect(page.locator('#detour')).toBeVisible();
 await page.evaluate(()=>{showView('sug');resetResult('sug');});
 await expect(page.locator('#sugResult')).toContainText('条件を設定してください');
 expect(errors).toEqual([]);
});
test('service worker and cached regional data',async({page,context})=>{
 await page.goto('http://127.0.0.1:8765/');
 await page.evaluate(()=>navigator.serviceWorker.ready);
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
 await page.evaluate(async()=>{await window.SugorokuLandUI.prepare({lat:34.3992388,lng:132.4406034});});
 await expect.poll(()=>page.evaluate(async()=>{const keys=await caches.keys();for(const k of keys){if(await (await caches.open(k)).match('./data/land-runtime/132_34.json'))return true;}return false;})).toBe(true);
 await context.setOffline(true);
 await page.reload();
 await page.waitForFunction(()=>typeof runSugoroku==='function'&&!document.body.classList.contains('pwa-starting'));
 await page.evaluate(()=>{showView('sug');setOrigin('sug',34.3992388,132.4406034,'広島試験地点');document.getElementById('sugRadiusFree').value='80';});
 await page.locator('#sug .action-main').click();await expect(page.locator('#sugResult .goal')).toBeVisible({timeout:60000});
 await context.setOffline(false);
});
