const assert=require("node:assert/strict");
const {create,km,factorForTarget}=require("../land-distance.js");
const {plan}=require("../budget-sugoroku.js");
const {band,within}=require("../distance-gacha.js");
require("../sugoroku-route.js");
const route=globalThis.SugorokuRoute;
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,a+" != "+b);
for(const [target,factor] of [[1,1.45],[50,1.45],[75,1.475],[100,1.5],[150,1.55],[200,1.6],[300,1.7],[400,1.775],[500,1.85],[625,1.875],[750,1.9],[1000,2],[2000,2]])close(factorForTarget(target),factor);
assert.equal(factorForTarget(null),1.45);
const p=(lng,landId,id)=>({lat:34,lng,landId,id,name:id});
const origin=p(132,"A","origin"),a=p(133,"A","a"),b=p(134,"A","b"),c=p(135,"A","c"),bridgeA=p(135.5,"A","bridgeA"),bridgeB=p(135.6,"B","bridgeB"),other=p(136,"B","other");
const lookup={classify(lat,lng){return {status:"land",landId:lng<135.55?"A":"B"};}};
const bridgeKm=15;
const connections=[{id:"bridge",type:"bridge",a:bridgeA,b:bridgeB,vehicles:["125"],km:bridgeKm}];
const old=create({lookup,connections}),engine=create({lookup,connections,factor:factorForTarget(500)});
close(old.estimate(origin,a).km,km(origin,a)*1.45);
close(engine.estimate(origin,a).km,km(origin,a)*1.85);
const trip=engine.itinerary(origin,[a,b,c]);
close(trip.km,trip.sections.reduce((s,x)=>s+x.km,0));
const cross=engine.estimate(bridgeA,bridgeB,{vehicle:"125"});
close(cross.km,bridgeKm);assert.deepEqual(cross.crossings,["bridge"]);
assert.equal(engine.estimate(origin,other,{vehicle:"126"}),null);
assert.equal(engine.estimate(origin,other,{vehicle:"125",sea:"none"}),null);
assert.equal(create({lookup,connections:[],factor:1.85}).estimate(origin,other),null);
const selected=plan(origin,[a,b,c],500,3,engine,route,{vehicle:"125"},()=>.5);
assert.ok(selected&&selected.km<=500);
close(selected.km,selected.estimate.km);
assert.ok(band(origin,[a,b,c],500,100,engine).every(x=>x.d>=400&&x.d<=600));
assert.ok(within(origin,[a,b,c],500,engine).every(x=>x.d<=500));
console.log("Ver12 factor, fixed crossing length, budget and band: PASS");
